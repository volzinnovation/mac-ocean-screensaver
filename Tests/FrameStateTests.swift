import Foundation
import simd

@main
enum FrameStateTests {
    private static var assertions = 0

    static func main() {
        check(OceanFrameState.grid == 32 && OceanFrameState.cascades == 6 && OceanFrameState.fftSize == 256,
              "source simulation dimensions")
        check(OceanFrameState.foamResolution == 1024 && OceanFrameState.instanceCapacity == 8192, "source resource dimensions")
        let indices = OceanFrameState.gridIndices
        check(indices.count == 32 * 32 * 6 && indices.max() == 1088, "grid index range")
        check(Array(indices.prefix(6)) == [0, 33, 34, 0, 34, 1], "grid triangle winding")
        let initial = OceanFrameState()
        check(initial.frameUniforms.count == 96 && initial.simulationUniforms.count == 56 && initial.foamUniforms.count == 36,
              "uniform ABI sizes")
        check(hash(initial.simulationUniforms) == 4094725645, "upstream static spectrum uniform bytes")

        // Generated by executing the original main.js writeFrame/selectAll code
        // in Node, not this port. Hashes are FNV-1a over Float32 bytes.
        let fixtures: [(Double, Int, Int, Int, UInt32, UInt32)] = [
            (0, 1920, 1080, 906, 3479084538, 861773300),
            (90, 1920, 1080, 906, 1729139914, 1859661331),
            (180, 1920, 1080, 906, 2276058202, 1712573556),
            (270, 1920, 1080, 906, 2834796842, 3107724380),
            (37, 1920, 1080, 893, 4017773449, 482651450),
            (37, 720, 1280, 465, 753255829, 2746088055),
            (0, 64, 64, 652, 3012287856, 942523112)
        ]
        for (azimuth, width, height, count, instanceHash, frameHash) in fixtures {
            let state = OceanFrameState()
            state.update(width: width, height: height, deltaTime: 0.05, sun: sun(azimuth: azimuth, elevation: 2.6))
            check(state.instances.count == count, "upstream visible node count at \(azimuth)°, \(width)×\(height)")
            check(hash(state.instances) == instanceHash, "upstream selected node bytes at \(azimuth)°")
            check(hash(state.frameUniforms) == frameHash,
                  "upstream frame bytes at \(azimuth)°: got \(hash(state.frameUniforms)), expected \(frameHash)")
            check(state.frameIndex == 1 && state.frameUniforms[70] == 1, "frame counter ABI")
            near(state.simulationUniforms[52], 0.05, tolerance: 1e-7, "spectrum time")
            near(state.simulationUniforms[53], 0.05, tolerance: 1e-7, "spectrum delta")
            validateNodes(state.instances)
            validateProjection(state)
        }

        let state = OceanFrameState()
        state.update(width: 1920, height: 1080, deltaTime: 0.05, sun: sun(azimuth: 0, elevation: 3))
        for level in 0..<2 {
            check(state.foamUniforms[level * 4].bitPattern == 0 && state.foamUniforms[level * 4 + 1].bitPattern == 0,
                  "foam clipmap current centre raw Int32")
            check(Int32(bitPattern: state.foamUniforms[level * 4 + 2].bitPattern) == 100000 &&
                  Int32(bitPattern: state.foamUniforms[level * 4 + 3].bitPattern) == 100000,
                  "first foam frame resets previous window by raw Int32")
        }
        near(state.foamUniforms[8], 0.125, tolerance: 0, "near foam texel width")
        near(state.foamUniforms[9], 1, tolerance: 0, "far foam texel width")
        state.update(width: 1920, height: 1080, deltaTime: 0.05, sun: sun(azimuth: 0, elevation: -20))
        check(state.foamUniforms[2].bitPattern == 0 && state.foamUniforms[3].bitPattern == 0 &&
              state.foamUniforms[6].bitPattern == 0 && state.foamUniforms[7].bitPattern == 0,
              "later foam frames retain zero snapped centre")
        check(state.frameUniforms[33] < 0, "night sun stays below horizon")
        near(state.time, 0.1, tolerance: 1e-6, "accumulated simulation time")

        state.waterHeight = 4
        state.update(width: 1920, height: 1080, deltaTime: 0.1, sun: sun(azimuth: 70, elevation: 40))
        near(state.cameraHeight, 4.9, tolerance: 1e-6, "camera rides above crest")
        state.waterHeight = -2
        state.update(width: 1920, height: 1080, deltaTime: 0.1, sun: sun(azimuth: 70, elevation: 40))
        near(state.cameraHeight, 4.9, tolerance: 1e-6, "upstream camera never lowers")
        state.waterHeight = .nan
        state.update(width: 0, height: 0, deltaTime: .nan, sun: sun(azimuth: 0, elevation: 0))
        check(state.frameUniforms.allSatisfy(\.isFinite), "invalid probe/delta and zero extent remain finite")
        check(state.frameUniforms[36] == 1 && state.frameUniforms[37] == 1, "zero extents clamp safely")

        // Solar geometry at both poles must pack finite, normalized directions.
        let date = ISO8601DateFormatter().date(from: "2024-06-20T20:51:00Z")!
        for latitude in [-90.0, 90.0] {
            let position = SolarPosition.calculate(date: date, coordinate: GeographicCoordinate(latitude: latitude, longitude: 0))!
            state.update(width: 1920, height: 1080, deltaTime: 1 / 30, sun: position)
            check(state.frameUniforms.allSatisfy(\.isFinite), "polar frame uniforms finite")
            let direction = SIMD3(state.frameUniforms[32], state.frameUniforms[33], state.frameUniforms[34])
            near(simd_length(direction), 1, tolerance: 1e-6, "polar sun unit vector")
        }
        for azimuth in stride(from: 0.0, to: 360, by: 15) {
            state.update(width: 2560, height: 1440, deltaTime: 1 / 30, sun: sun(azimuth: azimuth, elevation: 20))
            let camera = simd_normalize(SIMD2(state.frameUniforms[28], state.frameUniforms[30]))
            let light = simd_normalize(SIMD2(state.frameUniforms[32], state.frameUniforms[34]))
            near(simd_dot(camera, light), 1, tolerance: 1e-6, "camera always faces solar azimuth")
            check(!state.instances.isEmpty && state.instances.count <= OceanFrameState.instanceCapacity, "full heading sweep capacity")
        }

        // Avoid 600 seconds of wall-clock work while validating the closed loop.
        for _ in 0..<6001 { state.update(width: 64, height: 64, deltaTime: 0.1, sun: sun(azimuth: 0, elevation: 0)) }
        check(state.time >= 0 && state.time <= 600 && state.frameUniforms[19] == state.time &&
              state.frameUniforms[95] == state.time, "600-second spectrum/cloud time loop")
        print("OceanFrameState: \(assertions) assertions passed")
    }

    private static func sun(azimuth: Double, elevation: Double) -> SolarPosition {
        SolarPosition(azimuthDegrees: azimuth, elevationDegrees: elevation, apparentElevationDegrees: elevation)
    }

    private static func validateProjection(_ state: OceanFrameState) {
        let forward = SIMD3(state.frameUniforms[28], state.frameUniforms[29], state.frameUniforms[30])
        let nearClip = state.viewProjection * SIMD4(forward * 0.05, 1)
        let farClip = state.viewProjection * SIMD4(forward * 10000, 1)
        near(nearClip.z / nearClip.w, 1, tolerance: 1e-5, "reverse-Z near depth")
        near(farClip.z / farClip.w, 0.000005, tolerance: 1e-9, "reverse-Z far depth")
        near(nearClip.x / nearClip.w, 0, tolerance: 1e-5, "forward projects to screen centre x")
        near(nearClip.y / nearClip.w, 0, tolerance: 1e-5, "forward projects to screen centre y")
    }

    private static func validateNodes(_ nodes: [SIMD4<Float>]) {
        check(nodes.count <= OceanFrameState.instanceCapacity, "instance capacity")
        var keys = Set<String>()
        for node in nodes {
            check(node.z == 2 * pow(2, node.w) && (0...16).contains(node.w), "LOD node dimensions")
            check(node.x.truncatingRemainder(dividingBy: node.z) == 0 &&
                  node.y.truncatingRemainder(dividingBy: node.z) == 0, "node grid alignment")
            check(keys.insert("\(node.x),\(node.y),\(node.z)").inserted, "no duplicate node")
        }
        // Independent geometric check: no parent and child tile may coexist.
        for i in nodes.indices {
            for j in (i + 1)..<nodes.count {
                let a = nodes[i], b = nodes[j]
                let overlaps = max(a.x, b.x) < min(a.x + a.z, b.x + b.z) &&
                    max(a.y, b.y) < min(a.y + a.z, b.y + b.z)
                if overlaps { check(false, "CDLOD nodes overlap") }
            }
        }
        check(true, "CDLOD tessellation has no overlaps")
    }

    private static func hash<T>(_ values: [T]) -> UInt32 {
        values.withUnsafeBytes { bytes in
            bytes.reduce(UInt32(2166136261)) { ($0 ^ UInt32($1)) &* 16777619 }
        }
    }

    private static func near(_ actual: Float, _ expected: Float, tolerance: Float, _ message: String) {
        check(abs(actual - expected) <= tolerance, "\(message): expected \(expected), got \(actual)")
    }

    private static func check(_ condition: Bool, _ message: String) {
        assertions += 1
        if !condition { fputs("FAIL: \(message)\n", stderr); exit(1) }
    }
}
